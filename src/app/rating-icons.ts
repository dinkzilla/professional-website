export class RatingIcons {
  protected readonly chefKiss = CHEF_KISS;
  readonly criterion = input.required<string>();
  readonly value = input(0);
  /** Draw just one icon (for a button), lit or greyed by `off`, instead of the whole rating. */
  readonly single = input(false, { transform: booleanAttribute });
  readonly off = input(false);

  protected readonly icon = computed(() => ICONS[this.criterion()] ?? 'cane');
  protected readonly tally = computed(() => ['lips', 'heart', 'chef', 'shades', 'sign', 'note', 'bonus-star'].includes(this.icon()));
  protected readonly slots = computed(() => (this.tally() ? [] : this.single() ? [1] : [1, 2, 3, 4, 5]));
  protected readonly tallied = computed(() => Array.from({ length: Math.ceil(this.value()) }, (_, i) => i + 1));
  protected readonly label = computed(() => (this.tally() ? fmt(this.value()) : this.count() + ' out of 5'));
  protected readonly count = computed(() => Math.max(1, Math.min(5, Math.round(this.value()))));
}
